export const talentCopy: Readonly<Record<"sv" | "en", Record<TalentCopyKey, string>>> = { sv, en };

export function useTalentCopy(): { tt: (key: string) => string; lang: "sv" | "en" } {
  const { lang } = useT();
  const l: "sv" | "en" = lang === "en" ? "en" : "sv";
  // Unknown keys fall back to the key itself; model.ts only produces known ones.
  const tt = useCallback((key: string) => talentCopy[l][key as TalentCopyKey] ?? key, [l]);
  return { tt, lang: l };
}
