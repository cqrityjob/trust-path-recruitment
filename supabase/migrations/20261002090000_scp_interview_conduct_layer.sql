-- ============================================================================
-- The TRUST conduct layer — how the interviewer behaves, as governed content
-- ============================================================================
--
-- The live Copilot already showed 5E and the prohibited areas. It did not say
-- how to actually run the conversation, so the sequencing lived in whatever the
-- interviewer remembered. That is the gap this closes, and it closes it as
-- DATA rather than as a paragraph in the application: six ordered steps and a
-- list of things that must never be attempted, both pinned to the TRUST method
-- version so an interview can be audited against the conduct it was run under.
--
-- Three properties this migration exists to guarantee:
--
--   1. DETERMINISTIC. These are rows. Nothing generates them, no model is
--      consulted, and the Understand stage's zero-AI boundary is untouched.
--   2. ORDERED AND COMPLETE. Exactly six steps, ordinals 1-6, no gaps and no
--      duplicates, enforced by constraints and re-checked at the end.
--   3. BILINGUAL. Both columns are NOT NULL. Conduct guidance an interviewer
--      cannot read is not guidance, and the prohibitions least of all.
--
-- What the prohibitions are for: this is a structured interview about work
-- examples, not an interrogation. The named techniques below come from
-- investigative and deception-detection traditions where the goal is to obtain
-- an admission. Importing them into hiring produces pressure, not evidence, and
-- the inferences they invite -- credibility, cooperation, personality -- are
-- exactly the ones this engine refuses to make anywhere else. Naming them
-- specifically matters: "be fair" is advice, "do not use minimization" is a
-- boundary someone can be held to.
-- ============================================================================

CREATE TABLE public.scp_interview_conduct_steps (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  method_id uuid NOT NULL REFERENCES public.scp_interview_methods(id) ON DELETE CASCADE,

  step_key text NOT NULL CHECK (step_key IN (
    'invite', 'listen', 'reflect', 'clarify', 'substantiate', 'confirm')),
  ordinal integer NOT NULL CHECK (ordinal BETWEEN 1 AND 6),

  label_sv text NOT NULL,
  label_en text NOT NULL,
  guidance_sv text NOT NULL,
  guidance_en text NOT NULL,

  created_at timestamptz NOT NULL DEFAULT now(),

  UNIQUE (method_id, step_key),
  UNIQUE (method_id, ordinal)
);

COMMENT ON TABLE public.scp_interview_conduct_steps IS
  'The interviewer conduct sequence, as governed content pinned to a TRUST '
  'method version. Rendered during the live interview and generated by '
  'nothing: the Understand stage permits zero AI tasks, and this table is how '
  'the interviewer gets support there without a model being involved.';

CREATE TABLE public.scp_interview_conduct_prohibitions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  method_id uuid NOT NULL REFERENCES public.scp_interview_methods(id) ON DELETE CASCADE,

  prohibition_key text NOT NULL,
  statement_sv text NOT NULL,
  statement_en text NOT NULL,
  display_order integer NOT NULL DEFAULT 1,

  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (method_id, prohibition_key)
);

COMMENT ON TABLE public.scp_interview_conduct_prohibitions IS
  'What an interviewer must never attempt, named specifically enough to be '
  'held to. Separate from scp_interview_prohibited_areas, which is about '
  'SUBJECTS that may not be asked about; this is about TECHNIQUES that may not '
  'be used, whatever the subject.';

CREATE INDEX scp_interview_conduct_steps_method_idx
  ON public.scp_interview_conduct_steps (method_id, ordinal);
CREATE INDEX scp_interview_conduct_prohibitions_method_idx
  ON public.scp_interview_conduct_prohibitions (method_id, display_order);


-- ────────────────────────────────────────────────────────────────────────────
-- Grants and RLS. Same shape as the method practices these sit beside: an
-- active employer member may READ, nobody but the platform may write. Note the
-- REVOKE before every GRANT -- default privileges on this project hand new
-- tables to anon otherwise.
-- ────────────────────────────────────────────────────────────────────────────
ALTER TABLE public.scp_interview_conduct_steps ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.scp_interview_conduct_prohibitions ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.scp_interview_conduct_steps FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.scp_interview_conduct_prohibitions FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.scp_interview_conduct_steps TO authenticated;
GRANT SELECT ON public.scp_interview_conduct_prohibitions TO authenticated;
GRANT ALL ON public.scp_interview_conduct_steps TO service_role;
GRANT ALL ON public.scp_interview_conduct_prohibitions TO service_role;

CREATE POLICY scp_interview_conduct_steps_read ON public.scp_interview_conduct_steps
  FOR SELECT TO authenticated USING (
    public.scp_interview_can_read(auth.uid())
    OR EXISTS (SELECT 1 FROM public.employer_memberships em
                WHERE em.user_id = auth.uid() AND em.status = 'active'));

CREATE POLICY scp_interview_conduct_prohibitions_read ON public.scp_interview_conduct_prohibitions
  FOR SELECT TO authenticated USING (
    public.scp_interview_can_read(auth.uid())
    OR EXISTS (SELECT 1 FROM public.employer_memberships em
                WHERE em.user_id = auth.uid() AND em.status = 'active'));


