-- ────────────────────────────────────────────────────────────────────────────
-- Self-check. The conduct layer is either complete and readable, or the
-- migration fails: half a sequence on an interviewer's screen is worse than
-- none, because it looks finished.
-- ────────────────────────────────────────────────────────────────────────────
DO $$
DECLARE _methods integer; _bad integer;
BEGIN
  SELECT count(*) INTO _methods FROM public.scp_interview_methods;

  -- Six steps per method, ordinals 1-6, no gaps.
  SELECT count(*) INTO _bad FROM (
    SELECT s.method_id
      FROM public.scp_interview_conduct_steps s
     GROUP BY s.method_id
    HAVING count(*) <> 6
        OR array_agg(s.ordinal ORDER BY s.ordinal) <> ARRAY[1,2,3,4,5,6]
        OR array_agg(s.step_key ORDER BY s.ordinal)
           <> ARRAY['invite','listen','reflect','clarify','substantiate','confirm']
  ) q;
  IF _bad > 0 OR (SELECT count(DISTINCT method_id) FROM public.scp_interview_conduct_steps) <> _methods THEN
    RAISE EXCEPTION
      'SCP_IV_CONDUCT: the conduct sequence is incomplete on % method(s). Six '
      'ordered steps, invite through confirm, or none.', greatest(_bad, 1);
  END IF;

  -- Eight prohibitions per method, and every one of them readable twice.
  IF (SELECT count(*) FROM public.scp_interview_conduct_prohibitions) <> _methods * 8 THEN
    RAISE EXCEPTION 'SCP_IV_CONDUCT: expected 8 conduct prohibitions per method.';
  END IF;

  SELECT count(*) INTO _bad FROM public.scp_interview_conduct_steps
   WHERE btrim(label_en) = '' OR btrim(guidance_en) = ''
      OR btrim(label_sv) = '' OR btrim(guidance_sv) = '';
  IF _bad > 0 THEN
    RAISE EXCEPTION 'SCP_IV_CONDUCT: % conduct step(s) do not read in both languages.', _bad;
  END IF;

  SELECT count(*) INTO _bad FROM public.scp_interview_conduct_prohibitions
   WHERE btrim(statement_en) = '' OR btrim(statement_sv) = '';
  IF _bad > 0 THEN
    RAISE EXCEPTION 'SCP_IV_CONDUCT: % conduct prohibition(s) do not read in both languages.', _bad;
  END IF;

  -- The named techniques must actually be named. A generic "be fair" list
  -- would pass every count above while prohibiting nothing in particular.
  IF NOT EXISTS (SELECT 1 FROM public.scp_interview_conduct_prohibitions
                  WHERE statement_en ILIKE '%Scharff%' AND statement_en ILIKE '%Reid%'
                    AND statement_en ILIKE '%minimization%') THEN
    RAISE EXCEPTION
      'SCP_IV_CONDUCT: the interrogation techniques must be named explicitly. '
      'A named technique is a boundary; "be fair" is advice.';
  END IF;

  RAISE NOTICE
    'SCP_IV_CONDUCT: six ordered conduct steps and eight named prohibitions '
    'on % method(s), in both languages, generated by nothing.', _methods;
END $$;
